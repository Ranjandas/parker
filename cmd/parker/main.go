// layers are the --overlay, --var and --set flags.
func layers() (spec.Layers, error) {
	vars := map[string]string{}
	for _, kv := range varFlags {
		k, v, ok := strings.Cut(kv, "=")
		if !ok {
			return spec.Layers{}, fmt.Errorf("--var %q: want name=value", kv)
		}
		vars[k] = v
	}
	return spec.Layers{Overlays: overlayFlags, Vars: vars, Sets: setFlags}, nil
}

func load(path string) (*spec.File, *spec.File, error) {
	l, err := layers()
	if err != nil {
		return nil, nil, err
	}
	f, err := spec.LoadWith(path, l)
	if err != nil {
		return nil, nil, err
	}
	low, err := expand.Expand(f)
	return f, low, err
}

func say(format string, a ...any) { fmt.Printf(format+"\n", a...) }

func firstNode(f *spec.File) string {
	ks := slices.Sorted(maps.Keys(f.Nodes))
	if len(ks) == 0 {
		return "NODE"
	}
	return ks[0]
}

func labName(arg string) (string, error) {
	if _, err := os.Stat(arg); err == nil {
		l, err := layers()
		if err != nil {
			return "", err
		}
		f, err := spec.LoadWith(arg, l)
		if err != nil {
			return "", err
		}
		return f.Name, nil
	}
	return arg, nil
}

func expandCmd() *cobra.Command {
	var merged bool
	c := &cobra.Command{
		Use:   "expand FILE",
		Short: "Print the fully expanded, low-level form of a topology (itself valid input)",
		Args:  cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			if merged {
				l, err := layers()
				if err != nil {
					return err
				}
				if _, err := spec.LoadWith(args[0], l); err != nil {
					return err
				}
				text, err := spec.Merged(args[0], l)
				if err != nil {
					return err
				}
				os.Stdout.Write(text)
				return nil
			}
			_, low, err := load(args[0])
			if err != nil {
				return err
			}
			b, err := yaml.MarshalWithOptions(low, yaml.UseLiteralStyleIfMultiline(true), yaml.IndentSequence(true))
			if err != nil {
				return err
			}
			fmt.Print("# generated by `parker expand`; valid input for `parker up`\n")
			os.Stdout.Write(b)
			return nil
		},
	}
	c.Flags().BoolVar(&merged, "merged", false, "print FILE with --overlay and --set applied, before expansion")
	return c
}

func validateCmd() *cobra.Command {
	return &cobra.Command{
		Use:   "validate FILE",
		Short: "Check a topology file",
		Args:  cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			_, low, err := load(args[0])
			if err != nil {
				return err
			}
			// A host clash is only a warning here: the file may be meant
			// for another machine. `up` refuses it.
			if err := netsetup.CheckSubnets(low.Name, low); err != nil {
				fmt.Fprintf(os.Stderr, "warning: %v\n", err)
			}
			for _, w := range compat.Warnings(low) {
				fmt.Fprintf(os.Stderr, "warning: %s\n", w)
			}
			say("ok: %d networks, %d nodes", len(low.Networks), len(low.Nodes))
			return nil
		},
	}
}

func fetchCmd() *cobra.Command {
	return &cobra.Command{
		Use:   "fetch FILE",
		Short: "Download the binaries a topology pins into the cache",
		Args:  cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			_, low, err := load(args[0])
			if err != nil {
				return err
			}
			for _, pv := range wantedBinaries(low) {
				b, err := fetch.Binary(pv[0], pv[1], os.Stdout)
				if err != nil {
					return err
				}
				say("%s %s: %s", pv[0], pv[1], b)
			}
			return nil
		},
	}
}

